    #[test]
    #[ignore = "writes and rereads the frozen 6,442,975,232-byte production contribution"]
    fn full_scale_production_generation_is_an_explicit_operator_test() {
        let path = temp_path("full-scale-ignored");
        let report = generate_production_dory_v3_model_contribution(&path).unwrap();
        assert_eq!(report.contribution_bytes, 6_442_975_232);
        assert_eq!(
            fs::metadata(&path).unwrap().len(),
            report.contribution_bytes
        );
        assert_eq!(
            report.source_bytes_consumed,
            report
                .contribution_bytes
                .checked_add(report.rejected_source_bytes)
                .unwrap()
        );

        let mut file = File::open(&path).unwrap();
        let mut buffer = vec![0_u8; PRODUCTION_BUFFER_BYTES];
        let mut observed = 0_u64;
        let mut blake3 = blake3::Hasher::new();
        let mut sha256 = Sha256::new();
        loop {
            let read = file.read(&mut buffer).unwrap();
            if read == 0 {
                break;
            }
            assert!(buffer[..read].iter().all(|value| *value <= MAX_MODEL_BYTE));
            observed = observed.checked_add(u64::try_from(read).unwrap()).unwrap();
            blake3.update(&buffer[..read]);
            sha256.update(&buffer[..read]);
        }
        assert_eq!(observed, report.contribution_bytes);
        assert_eq!(file.read(&mut [0_u8; 1]).unwrap(), 0);
        assert_eq!(
            *blake3.finalize().as_bytes(),
            report.contribution_blake3.into_bytes()
        );
        assert_eq!(
            finalize_sha256(sha256),
            report.contribution_sha256.into_bytes()
        );
        fs::remove_file(path).unwrap();
    }
