//! Full-length production contribution generation for the Dory V3 model ceremony.
//!
//! The public entry point has no seed or geometry inputs. It rejection-samples
//! directly from the operating-system CSPRNG into the one frozen production
//! length, then reopens and authenticates the retained output before success.
//! Its JSON report is operational output, not ceremony transcript evidence.
//!
//! Publication assumes the operator-owned local-directory boundary required by
//! the ceremony protocol. A crash can leave a partial file that must be
//! quarantined; this module does not claim safety in a hostile shared directory.
//! On Windows, an operator-only parent-directory DACL is a prerequisite that
//! this portable implementation does not attempt to infer.

use std::{
    fs::{self, File, OpenOptions},
    io::{Read, Write},
    path::{Path, PathBuf},
    time::{Duration, Instant},
};

use rand_core::{OsRng, RngCore};
use same_file::Handle as SameFileHandle;
use serde::Serialize;
use sha2::{Digest as _, Sha256};
use thiserror::Error;

use crate::{
    MAX_MODEL_BYTE,
    dory_v3_suite::{DORY_V3_BATCH, DORY_V3_DIMENSION, DORY_V3_LAYERS, Digest32},
};

const FROZEN_PRODUCTION_CONTRIBUTION_BYTES: u64 = 6_442_975_232;
const PRODUCTION_BUFFER_BYTES: usize = 1_048_576;

/// Audit-only result emitted after the generated contribution has been
/// reopened, range-checked, dual-hashed, and identity-checked.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct ProductionDoryV3ModelContributionReport {
    pub output: PathBuf,
    pub contribution_bytes: u64,
    pub source_bytes_consumed: u64,
    pub rejected_source_bytes: u64,
    pub contribution_blake3: Digest32,
    pub contribution_sha256: Digest32,
    pub generation_elapsed_micros: u64,
    pub verification_elapsed_micros: u64,
}

/// Fail-closed errors from full-length production contribution generation.
#[derive(Debug, Error)]
pub enum ProductionDoryV3ModelContributionError {
    #[error("the compiled production contribution geometry overflowed")]
    GeometryOverflow,
    #[error("the compiled production contribution geometry is not the frozen ceremony geometry")]
    ProductionGeometryMismatch,
    #[error("refusing to run because the output path already exists: {0}")]
    OutputExists(PathBuf),
    #[error("output path is not an ordinary local file path: {0}")]
    InvalidOutputPath(PathBuf),
    #[error("output parent is not a real non-reparse directory: {0}")]
    UnsafeOutputParent(PathBuf),
    #[error("failed to inspect output path {path}: {source}")]
    InspectOutput {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },
    #[error("failed to create new output file {path}: {source}")]
    CreateOutput {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },
    #[error("the operating-system CSPRNG failed: {0}")]
    Entropy(#[source] rand_core::Error),
    #[error("generation byte accounting overflowed")]
    CountOverflow,
    #[error("failed to allocate the bounded generation buffer")]
    BufferAllocation,
    #[error("failed to write new output file {path}: {source}")]
    WriteOutput {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },
    #[error("failed to flush new output file {path}: {source}")]
    FlushOutput {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },
    #[error("failed to sync new output file {path}: {source}")]
    SyncOutput {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },
    #[error("failed to reopen or read output file {path}: {source}")]
    ReadOutput {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },
    #[error("output path is not a regular file: {0}")]
    OutputNotRegular(PathBuf),
    #[error("output file has {links} hard links instead of exactly one: {path}")]
    UnexpectedHardLinks { path: PathBuf, links: u64 },
    #[error("this target cannot verify that the output has exactly one hard link: {0}")]
    HardLinkCountUnsupported(PathBuf),
    #[error("output path was replaced or no longer names the retained file: {0}")]
    OutputIdentityMismatch(PathBuf),
    #[error("output length mismatch: expected {expected} bytes, observed {actual}")]
    OutputLengthMismatch { expected: u64, actual: u64 },
    #[error("output byte {value} at offset {offset} exceeds the maximum value 250")]
    OutputByteOutOfRange { offset: u64, value: u8 },
    #[error("the reopened output digests differ from the generated byte stream")]
    OutputDigestMismatch,
    #[error("failed to remove unconfirmed output {path}: {source}")]
    Cleanup {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },
    #[error("failed to sync output parent {path}: {source}")]
    SyncParent {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },
    #[error("parent-directory synchronization is unsupported for {path}: {source}")]
    ParentDirectorySyncUnsupported {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },
}

#[derive(Debug, Clone, Copy)]
struct ContributionGeometry {
    contribution_bytes: u64,
    maximum_accepted_byte: u8,
    buffer_bytes: usize,
}

impl ContributionGeometry {
    fn production() -> Result<Self, ProductionDoryV3ModelContributionError> {
        let base_input_bytes = u64::from(DORY_V3_BATCH)
            .checked_mul(u64::from(DORY_V3_DIMENSION))
            .ok_or(ProductionDoryV3ModelContributionError::GeometryOverflow)?;
        let bytes_per_layer = u64::from(DORY_V3_DIMENSION)
            .checked_mul(u64::from(DORY_V3_DIMENSION))
            .ok_or(ProductionDoryV3ModelContributionError::GeometryOverflow)?;
        let weight_bytes = u64::from(DORY_V3_LAYERS)
            .checked_mul(bytes_per_layer)
            .ok_or(ProductionDoryV3ModelContributionError::GeometryOverflow)?;
        let contribution_bytes = base_input_bytes
            .checked_add(weight_bytes)
            .ok_or(ProductionDoryV3ModelContributionError::GeometryOverflow)?;
        if contribution_bytes != FROZEN_PRODUCTION_CONTRIBUTION_BYTES
            || MAX_MODEL_BYTE != 250
            || PRODUCTION_BUFFER_BYTES > 1_048_576
        {
            return Err(ProductionDoryV3ModelContributionError::ProductionGeometryMismatch);
        }
        Ok(Self {
            contribution_bytes,
            maximum_accepted_byte: MAX_MODEL_BYTE,
            buffer_bytes: PRODUCTION_BUFFER_BYTES,
        })
    }

    fn validate(self) -> Result<(), ProductionDoryV3ModelContributionError> {
        if self.contribution_bytes == 0
            || self.maximum_accepted_byte != MAX_MODEL_BYTE
            || self.buffer_bytes == 0
            || self.buffer_bytes > 1_048_576
        {
            return Err(ProductionDoryV3ModelContributionError::ProductionGeometryMismatch);
        }
        Ok(())
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct GenerationStats {
    contribution_bytes: u64,
    source_bytes_consumed: u64,
    rejected_source_bytes: u64,
    blake3: [u8; 32],
    sha256: [u8; 32],
}

#[derive(Debug)]
enum StreamGenerationError {
    Entropy(rand_core::Error),
    Write(std::io::Error),
    CountOverflow,
    BufferAllocation,
}

/// Generate one exact production contribution using only `rand_core::OsRng`.
/// Existing paths are rejected and never overwritten. No compact seed or
/// caller-selected geometry is accepted.
pub fn generate_production_dory_v3_model_contribution(
    output_path: &Path,
) -> Result<ProductionDoryV3ModelContributionReport, ProductionDoryV3ModelContributionError> {
    let geometry = ContributionGeometry::production()?;
    let mut source = OsRng;
    generate_contribution_with_source(output_path, geometry, &mut source)
}

fn generate_contribution_with_source<R: RngCore>(
    output_path: &Path,
    geometry: ContributionGeometry,
    source: &mut R,
) -> Result<ProductionDoryV3ModelContributionReport, ProductionDoryV3ModelContributionError> {
    generate_contribution_with_source_and_parent_sync(
        output_path,
        geometry,
        source,
        sync_output_parent,
    )
}

fn generate_contribution_with_source_and_parent_sync<R, P>(
    output_path: &Path,
    geometry: ContributionGeometry,
    source: &mut R,
    sync_parent: P,
) -> Result<ProductionDoryV3ModelContributionReport, ProductionDoryV3ModelContributionError>
where
    R: RngCore,
    P: FnOnce(&Path) -> Result<(), ProductionDoryV3ModelContributionError>,
{
    geometry.validate()?;
    preflight_output_path(output_path)?;
    reject_existing_output(output_path)?;

    let generation_started = Instant::now();
    let (mut output, generated) = create_generated_output_with(
        output_path,
        geometry,
        source,
        |file, bytes| file.write_all(bytes),
        Write::flush,
        File::sync_all,
    )?;
    let generation_elapsed = generation_started.elapsed();

    let verification_started = Instant::now();
    let completion = (|| {
        let verified = authenticate_generated_output(&output, geometry, &generated)?;
        sync_parent(output_path)?;
        Ok(ProductionDoryV3ModelContributionReport {
            output: output_path.to_path_buf(),
            contribution_bytes: verified.contribution_bytes,
            source_bytes_consumed: generated.source_bytes_consumed,
            rejected_source_bytes: generated.rejected_source_bytes,
            contribution_blake3: Digest32::new(verified.blake3),
            contribution_sha256: Digest32::new(verified.sha256),
            generation_elapsed_micros: elapsed_micros(generation_elapsed),
            verification_elapsed_micros: elapsed_micros(verification_started.elapsed()),
        })
    })();
    finish_or_cleanup_output(&mut output, completion)
}

fn create_generated_output_with<R, W, F, S>(
    output_path: &Path,
    geometry: ContributionGeometry,
    source: &mut R,
    mut write_chunk: W,
    flush_file: F,
    sync_file: S,
) -> Result<(PublishedContributionOutput, GenerationStats), ProductionDoryV3ModelContributionError>
where
    R: RngCore,
    W: FnMut(&mut File, &[u8]) -> std::io::Result<()>,
    F: FnOnce(&mut File) -> std::io::Result<()>,
    S: FnOnce(&File) -> std::io::Result<()>,
{
    let mut options = OpenOptions::new();
    options.read(true).write(true).create_new(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;

        options.mode(0o600);
    }
    let file = options.open(output_path).map_err(|source| {
        if source.kind() == std::io::ErrorKind::AlreadyExists {
            ProductionDoryV3ModelContributionError::OutputExists(output_path.to_path_buf())
        } else {
            ProductionDoryV3ModelContributionError::CreateOutput {
                path: output_path.to_path_buf(),
                source,
            }
        }
    })?;
    // If identity capture fails, pathname cleanup could remove a concurrent
    // replacement. Propagate the error and leave the new path for inspection.
    let retained = retained_file_identity(file, output_path)?;
    let mut output = PublishedContributionOutput {
        path: output_path.to_path_buf(),
        expected_length: geometry.contribution_bytes,
        retained: Some(retained),
        finished: false,
    };
    let mut file = match output.identity()?.as_file().try_clone() {
        Ok(file) => file,
        Err(source) => {
            let error = ProductionDoryV3ModelContributionError::CreateOutput {
                path: output_path.to_path_buf(),
                source,
            };
            return Err(cleanup_after_error(&mut output, error));
        }
    };

    let generated = match generate_stream(source, geometry, |bytes| write_chunk(&mut file, bytes)) {
        Ok(generated) => generated,
        Err(error) => {
            drop(file);
            let error = match error {
                StreamGenerationError::Entropy(source) => {
                    ProductionDoryV3ModelContributionError::Entropy(source)
                }
                StreamGenerationError::Write(source) => {
                    ProductionDoryV3ModelContributionError::WriteOutput {
                        path: output_path.to_path_buf(),
                        source,
                    }
                }
                StreamGenerationError::CountOverflow => {
                    ProductionDoryV3ModelContributionError::CountOverflow
                }
                StreamGenerationError::BufferAllocation => {
                    ProductionDoryV3ModelContributionError::BufferAllocation
                }
            };
            return Err(cleanup_after_error(&mut output, error));
        }
    };
    if let Err(source) = flush_file(&mut file) {
        drop(file);
        let error = ProductionDoryV3ModelContributionError::FlushOutput {
            path: output_path.to_path_buf(),
            source,
        };
        return Err(cleanup_after_error(&mut output, error));
    }
    if let Err(source) = sync_file(&file) {
        drop(file);
        let error = ProductionDoryV3ModelContributionError::SyncOutput {
            path: output_path.to_path_buf(),
            source,
        };
        return Err(cleanup_after_error(&mut output, error));
    }
    drop(file);
    Ok((output, generated))
}

fn generate_stream<R, W>(
    source: &mut R,
    geometry: ContributionGeometry,
    mut write_chunk: W,
) -> Result<GenerationStats, StreamGenerationError>
where
    R: RngCore,
    W: FnMut(&[u8]) -> std::io::Result<()>,
{
    let mut buffer = Vec::new();
    buffer
        .try_reserve_exact(geometry.buffer_bytes)
        .map_err(|_| StreamGenerationError::BufferAllocation)?;
    buffer.resize(geometry.buffer_bytes, 0_u8);
    let mut accepted = 0_u64;
    let mut consumed = 0_u64;
    let mut rejected = 0_u64;
    let mut blake3 = blake3::Hasher::new();
    let mut sha256 = Sha256::new();

    while accepted < geometry.contribution_bytes {
        source
            .try_fill_bytes(&mut buffer)
            .map_err(StreamGenerationError::Entropy)?;
        let remaining = geometry
            .contribution_bytes
            .checked_sub(accepted)
            .ok_or(StreamGenerationError::CountOverflow)?;
        let buffer_len_u64 =
            u64::try_from(buffer.len()).map_err(|_| StreamGenerationError::CountOverflow)?;
        let accepted_limit = usize::try_from(remaining.min(buffer_len_u64))
            .map_err(|_| StreamGenerationError::CountOverflow)?;
        let mut accepted_in_chunk = 0_usize;
        let mut examined_in_chunk = 0_usize;

        for read_index in 0..buffer.len() {
            if accepted_in_chunk == accepted_limit {
                break;
            }
            let value = buffer[read_index];
            examined_in_chunk = examined_in_chunk
                .checked_add(1)
                .ok_or(StreamGenerationError::CountOverflow)?;
            if value <= geometry.maximum_accepted_byte {
                buffer[accepted_in_chunk] = value;
                accepted_in_chunk = accepted_in_chunk
                    .checked_add(1)
                    .ok_or(StreamGenerationError::CountOverflow)?;
            }
        }

        let accepted_in_chunk_u64 =
            u64::try_from(accepted_in_chunk).map_err(|_| StreamGenerationError::CountOverflow)?;
        let examined_in_chunk_u64 =
            u64::try_from(examined_in_chunk).map_err(|_| StreamGenerationError::CountOverflow)?;
        let rejected_in_chunk = examined_in_chunk_u64
            .checked_sub(accepted_in_chunk_u64)
            .ok_or(StreamGenerationError::CountOverflow)?;
        let accepted_bytes = &buffer[..accepted_in_chunk];
        write_chunk(accepted_bytes).map_err(StreamGenerationError::Write)?;
        blake3.update(accepted_bytes);
        sha256.update(accepted_bytes);

        accepted = accepted
            .checked_add(accepted_in_chunk_u64)
            .ok_or(StreamGenerationError::CountOverflow)?;
        consumed = consumed
            .checked_add(examined_in_chunk_u64)
            .ok_or(StreamGenerationError::CountOverflow)?;
        rejected = rejected
            .checked_add(rejected_in_chunk)
            .ok_or(StreamGenerationError::CountOverflow)?;
    }

    if consumed
        != accepted
            .checked_add(rejected)
            .ok_or(StreamGenerationError::CountOverflow)?
    {
        return Err(StreamGenerationError::CountOverflow);
    }
    Ok(GenerationStats {
        contribution_bytes: accepted,
        source_bytes_consumed: consumed,
        rejected_source_bytes: rejected,
        blake3: *blake3.finalize().as_bytes(),
        sha256: finalize_sha256(sha256),
    })
}

fn authenticate_generated_output(
    output: &PublishedContributionOutput,
    geometry: ContributionGeometry,
    generated: &GenerationStats,
) -> Result<GenerationStats, ProductionDoryV3ModelContributionError> {
    let verified = verify_output(output, geometry)?;
    if verified.contribution_bytes != generated.contribution_bytes
        || verified.blake3 != generated.blake3
        || verified.sha256 != generated.sha256
    {
        return Err(ProductionDoryV3ModelContributionError::OutputDigestMismatch);
    }
    Ok(verified)
}

fn verify_output(
    output: &PublishedContributionOutput,
    geometry: ContributionGeometry,
) -> Result<GenerationStats, ProductionDoryV3ModelContributionError> {
    let mut file = output.reopen_reader()?;
    let initial_length = file
        .metadata()
        .map_err(
            |source| ProductionDoryV3ModelContributionError::ReadOutput {
                path: output.path.clone(),
                source,
            },
        )?
        .len();
    if initial_length != geometry.contribution_bytes {
        return Err(
            ProductionDoryV3ModelContributionError::OutputLengthMismatch {
                expected: geometry.contribution_bytes,
                actual: initial_length,
            },
        );
    }

    let mut buffer = Vec::new();
    buffer
        .try_reserve_exact(geometry.buffer_bytes)
        .map_err(|_| ProductionDoryV3ModelContributionError::BufferAllocation)?;
    buffer.resize(geometry.buffer_bytes, 0_u8);
    let mut observed = 0_u64;
    let mut blake3 = blake3::Hasher::new();
    let mut sha256 = Sha256::new();
    while observed < geometry.contribution_bytes {
        let remaining = geometry.contribution_bytes - observed;
        let read_limit = usize::try_from(remaining.min(buffer.len() as u64))
            .map_err(|_| ProductionDoryV3ModelContributionError::CountOverflow)?;
        let read = file.read(&mut buffer[..read_limit]).map_err(|source| {
            ProductionDoryV3ModelContributionError::ReadOutput {
                path: output.path.clone(),
                source,
            }
        })?;
        if read == 0 {
            return Err(
                ProductionDoryV3ModelContributionError::OutputLengthMismatch {
                    expected: geometry.contribution_bytes,
                    actual: observed,
                },
            );
        }
        for (index, value) in buffer[..read].iter().copied().enumerate() {
            if value > geometry.maximum_accepted_byte {
                let offset = observed
                    .checked_add(
                        u64::try_from(index)
                            .map_err(|_| ProductionDoryV3ModelContributionError::CountOverflow)?,
                    )
                    .ok_or(ProductionDoryV3ModelContributionError::CountOverflow)?;
                return Err(
                    ProductionDoryV3ModelContributionError::OutputByteOutOfRange { offset, value },
                );
            }
        }
        blake3.update(&buffer[..read]);
        sha256.update(&buffer[..read]);
        observed = observed
            .checked_add(
                u64::try_from(read)
                    .map_err(|_| ProductionDoryV3ModelContributionError::CountOverflow)?,
            )
            .ok_or(ProductionDoryV3ModelContributionError::CountOverflow)?;
    }

    let mut trailing = [0_u8; 1];
    if file.read(&mut trailing).map_err(|source| {
        ProductionDoryV3ModelContributionError::ReadOutput {
            path: output.path.clone(),
            source,
        }
    })? != 0
    {
        return Err(
            ProductionDoryV3ModelContributionError::OutputLengthMismatch {
                expected: geometry.contribution_bytes,
                actual: geometry.contribution_bytes.saturating_add(1),
            },
        );
    }
    let final_length = file
        .metadata()
        .map_err(
            |source| ProductionDoryV3ModelContributionError::ReadOutput {
                path: output.path.clone(),
                source,
            },
        )?
        .len();
    if final_length != geometry.contribution_bytes {
        return Err(
            ProductionDoryV3ModelContributionError::OutputLengthMismatch {
                expected: geometry.contribution_bytes,
                actual: final_length,
            },
        );
    }

    Ok(GenerationStats {
        contribution_bytes: observed,
        source_bytes_consumed: 0,
        rejected_source_bytes: 0,
        blake3: *blake3.finalize().as_bytes(),
        sha256: finalize_sha256(sha256),
    })
}

fn finalize_sha256(hasher: Sha256) -> [u8; 32] {
    let digest = hasher.finalize();
    let mut bytes = [0_u8; 32];
    bytes.copy_from_slice(&digest);
    bytes
}

fn preflight_output_path(output_path: &Path) -> Result<(), ProductionDoryV3ModelContributionError> {
    let file_name = output_path
        .file_name()
        .filter(|name| !name.is_empty())
        .ok_or_else(|| {
            ProductionDoryV3ModelContributionError::InvalidOutputPath(output_path.to_path_buf())
        })?;

    #[cfg(windows)]
    {
        use std::{os::windows::ffi::OsStrExt, path::Component};

        // A colon in the terminal component selects an NTFS alternate data
        // stream rather than an independent ceremony artifact. Verbatim, UNC,
        // and device namespaces also bypass ordinary Win32 path semantics.
        let has_stream_separator = file_name.encode_wide().any(|unit| unit == u16::from(b':'));
        let has_nonlocal_prefix = matches!(
            output_path.components().next(),
            Some(Component::Prefix(prefix))
                if !matches!(prefix.kind(), std::path::Prefix::Disk(_))
        );
        if has_stream_separator || has_nonlocal_prefix {
            return Err(ProductionDoryV3ModelContributionError::InvalidOutputPath(
                output_path.to_path_buf(),
            ));
        }
    }

    let _ = file_name;
    let parent = output_parent(output_path);
    let metadata = fs::symlink_metadata(parent).map_err(|source| {
        ProductionDoryV3ModelContributionError::InspectOutput {
            path: parent.to_path_buf(),
            source,
        }
    })?;
    if !metadata.file_type().is_dir() {
        return Err(ProductionDoryV3ModelContributionError::UnsafeOutputParent(
            parent.to_path_buf(),
        ));
    }

    #[cfg(windows)]
    {
        use std::os::windows::fs::MetadataExt;

        validate_windows_parent_attributes(parent, metadata.file_attributes())?;
    }

    Ok(())
}

#[cfg(windows)]
fn validate_windows_parent_attributes(
    parent: &Path,
    attributes: u32,
) -> Result<(), ProductionDoryV3ModelContributionError> {
    const FILE_ATTRIBUTE_REPARSE_POINT: u32 = 0x0000_0400;
    if attributes & FILE_ATTRIBUTE_REPARSE_POINT != 0 {
        return Err(ProductionDoryV3ModelContributionError::UnsafeOutputParent(
            parent.to_path_buf(),
        ));
    }
    Ok(())
}

fn reject_existing_output(
    output_path: &Path,
) -> Result<(), ProductionDoryV3ModelContributionError> {
    match fs::symlink_metadata(output_path) {
        Ok(_) => Err(ProductionDoryV3ModelContributionError::OutputExists(
            output_path.to_path_buf(),
        )),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(source) => Err(ProductionDoryV3ModelContributionError::InspectOutput {
            path: output_path.to_path_buf(),
            source,
        }),
    }
}

fn finish_or_cleanup_output<T>(
    output: &mut PublishedContributionOutput,
    completion: Result<T, ProductionDoryV3ModelContributionError>,
) -> Result<T, ProductionDoryV3ModelContributionError> {
    match completion {
        Ok(value) => match output.ensure_current_path() {
            Ok(()) => {
                output.confirm();
                Ok(value)
            }
            Err(error) => Err(cleanup_after_error(output, error)),
        },
        Err(error) => Err(cleanup_after_error(output, error)),
    }
}

fn cleanup_after_error(
    output: &mut PublishedContributionOutput,
    error: ProductionDoryV3ModelContributionError,
) -> ProductionDoryV3ModelContributionError {
    match output.remove_explicit() {
        Ok(()) => error,
        Err(cleanup) => cleanup,
    }
}

fn retained_file_identity(
    file: File,
    path: &Path,
) -> Result<SameFileHandle, ProductionDoryV3ModelContributionError> {
    let metadata = file.metadata().map_err(|source| {
        ProductionDoryV3ModelContributionError::InspectOutput {
            path: path.to_path_buf(),
            source,
        }
    })?;
    validate_regular_output(&metadata, path)?;
    validate_single_link(&file, &metadata, path)?;
    SameFileHandle::from_file(file).map_err(|source| {
        ProductionDoryV3ModelContributionError::InspectOutput {
            path: path.to_path_buf(),
            source,
        }
    })
}

fn regular_path_identity(
    path: &Path,
) -> Result<SameFileHandle, ProductionDoryV3ModelContributionError> {
    let metadata = fs::symlink_metadata(path).map_err(|source| {
        ProductionDoryV3ModelContributionError::InspectOutput {
            path: path.to_path_buf(),
            source,
        }
    })?;
    validate_regular_output(&metadata, path)?;
    let file = File::open(path).map_err(|source| {
        ProductionDoryV3ModelContributionError::InspectOutput {
            path: path.to_path_buf(),
            source,
        }
    })?;
    let reopened_metadata = file.metadata().map_err(|source| {
        ProductionDoryV3ModelContributionError::InspectOutput {
            path: path.to_path_buf(),
            source,
        }
    })?;
    validate_regular_output(&reopened_metadata, path)?;
    validate_single_link(&file, &reopened_metadata, path)?;
    SameFileHandle::from_file(file).map_err(|source| {
        ProductionDoryV3ModelContributionError::InspectOutput {
            path: path.to_path_buf(),
            source,
        }
    })
}

fn ensure_path_identity(
    path: &Path,
    expected: &SameFileHandle,
) -> Result<(), ProductionDoryV3ModelContributionError> {
    if &regular_path_identity(path)? != expected {
        return Err(
            ProductionDoryV3ModelContributionError::OutputIdentityMismatch(path.to_path_buf()),
        );
    }
    Ok(())
}

fn remove_file_if_identity(
    path: &Path,
    expected: &SameFileHandle,
) -> Result<(), ProductionDoryV3ModelContributionError> {
    ensure_path_identity(path, expected).map_err(|error| cleanup_error(path, error.to_string()))?;
    fs::remove_file(path).map_err(|source| ProductionDoryV3ModelContributionError::Cleanup {
        path: path.to_path_buf(),
        source,
    })
}

fn cleanup_error(
    path: &Path,
    message: impl Into<String>,
) -> ProductionDoryV3ModelContributionError {
    ProductionDoryV3ModelContributionError::Cleanup {
        path: path.to_path_buf(),
        source: std::io::Error::other(message.into()),
    }
}

fn elapsed_micros(duration: Duration) -> u64 {
    u64::try_from(duration.as_micros()).unwrap_or(u64::MAX)
}

fn validate_regular_output(
    metadata: &fs::Metadata,
    path: &Path,
) -> Result<(), ProductionDoryV3ModelContributionError> {
    if !metadata.file_type().is_file() {
        return Err(ProductionDoryV3ModelContributionError::OutputNotRegular(
            path.to_path_buf(),
        ));
    }

    #[cfg(windows)]
    {
        use std::os::windows::fs::MetadataExt;

        const FILE_ATTRIBUTE_REPARSE_POINT: u32 = 0x0000_0400;
        if metadata.file_attributes() & FILE_ATTRIBUTE_REPARSE_POINT != 0 {
            return Err(ProductionDoryV3ModelContributionError::OutputNotRegular(
                path.to_path_buf(),
            ));
        }
    }
    Ok(())
}

fn validate_single_link(
    file: &File,
    metadata: &fs::Metadata,
    path: &Path,
) -> Result<(), ProductionDoryV3ModelContributionError> {
    #[cfg(unix)]
    let links = {
        use std::os::unix::fs::MetadataExt;

        let _ = file;
        metadata.nlink()
    };

    #[cfg(windows)]
    let links = {
        use std::{mem::MaybeUninit, os::windows::io::AsRawHandle};
        use windows_sys::Win32::Storage::FileSystem::{
            BY_HANDLE_FILE_INFORMATION, GetFileInformationByHandle,
        };

        let _ = metadata;
        let mut information = MaybeUninit::<BY_HANDLE_FILE_INFORMATION>::uninit();
        // SAFETY: `file` owns a live kernel handle and `information` points to
        // writable storage of the exact structure required by the Win32 API.
        let succeeded =
            unsafe { GetFileInformationByHandle(file.as_raw_handle(), information.as_mut_ptr()) };
        if succeeded == 0 {
            return Err(ProductionDoryV3ModelContributionError::InspectOutput {
                path: path.to_path_buf(),
                source: std::io::Error::last_os_error(),
            });
        }
        // SAFETY: a nonzero return guarantees the structure was initialized.
        u64::from(unsafe { information.assume_init() }.nNumberOfLinks)
    };

    #[cfg(not(any(unix, windows)))]
    {
        let _ = (file, metadata);
        return Err(
            ProductionDoryV3ModelContributionError::HardLinkCountUnsupported(path.to_path_buf()),
        );
    }

    #[cfg(any(unix, windows))]
    if links != 1 {
        return Err(
            ProductionDoryV3ModelContributionError::UnexpectedHardLinks {
                path: path.to_path_buf(),
                links,
            },
        );
    }
    Ok(())
}

fn output_parent(path: &Path) -> &Path {
    path.parent()
        .filter(|parent| !parent.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."))
}

fn sync_output_parent(path: &Path) -> Result<(), ProductionDoryV3ModelContributionError> {
    let parent = output_parent(path);

    #[cfg(unix)]
    let directory = File::open(parent).map_err(|source| {
        ProductionDoryV3ModelContributionError::SyncParent {
            path: parent.to_path_buf(),
            source,
        }
    })?;

    #[cfg(windows)]
    let directory = {
        use std::os::windows::fs::OpenOptionsExt;

        const FILE_FLAG_BACKUP_SEMANTICS: u32 = 0x0200_0000;
        OpenOptions::new()
            .read(true)
            .write(true)
            .custom_flags(FILE_FLAG_BACKUP_SEMANTICS)
            .open(parent)
            .map_err(|source| map_parent_sync_error(parent, source))?
    };

    #[cfg(not(any(unix, windows)))]
    return Err(
        ProductionDoryV3ModelContributionError::ParentDirectorySyncUnsupported {
            path: parent.to_path_buf(),
            source: std::io::Error::new(
                std::io::ErrorKind::Unsupported,
                "this target has no implemented directory synchronization primitive",
            ),
        },
    );

    #[cfg(any(unix, windows))]
    directory
        .sync_all()
        .map_err(|source| map_parent_sync_error(parent, source))
}

fn map_parent_sync_error(
    parent: &Path,
    source: std::io::Error,
) -> ProductionDoryV3ModelContributionError {
    #[cfg(windows)]
    if source.kind() == std::io::ErrorKind::Unsupported
        || matches!(source.raw_os_error(), Some(1 | 5 | 50))
    {
        return ProductionDoryV3ModelContributionError::ParentDirectorySyncUnsupported {
            path: parent.to_path_buf(),
            source,
        };
    }

    ProductionDoryV3ModelContributionError::SyncParent {
        path: parent.to_path_buf(),
        source,
    }
}

#[derive(Debug)]
struct PublishedContributionOutput {
    path: PathBuf,
    expected_length: u64,
    retained: Option<SameFileHandle>,
    finished: bool,
}

impl PublishedContributionOutput {
    fn identity(&self) -> Result<&SameFileHandle, ProductionDoryV3ModelContributionError> {
        self.retained.as_ref().ok_or_else(|| {
            ProductionDoryV3ModelContributionError::OutputIdentityMismatch(self.path.clone())
        })
    }

    fn reopen_reader(&self) -> Result<File, ProductionDoryV3ModelContributionError> {
        ensure_path_identity(&self.path, self.identity()?)?;
        let file = OpenOptions::new()
            .read(true)
            .open(&self.path)
            .map_err(
                |source| ProductionDoryV3ModelContributionError::ReadOutput {
                    path: self.path.clone(),
                    source,
                },
            )?;
        let reopened = file.try_clone().map_err(|source| {
            ProductionDoryV3ModelContributionError::ReadOutput {
                path: self.path.clone(),
                source,
            }
        })?;
        let reopened = retained_file_identity(reopened, &self.path)?;
        if &reopened != self.identity()? {
            return Err(
                ProductionDoryV3ModelContributionError::OutputIdentityMismatch(self.path.clone()),
            );
        }
        Ok(file)
    }

    fn ensure_current_path(&self) -> Result<(), ProductionDoryV3ModelContributionError> {
        let file = self.reopen_reader()?;
        let actual = file
            .metadata()
            .map_err(
                |source| ProductionDoryV3ModelContributionError::ReadOutput {
                    path: self.path.clone(),
                    source,
                },
            )?
            .len();
        if actual != self.expected_length {
            return Err(
                ProductionDoryV3ModelContributionError::OutputLengthMismatch {
                    expected: self.expected_length,
                    actual,
                },
            );
        }
        Ok(())
    }

    fn remove_explicit(&mut self) -> Result<(), ProductionDoryV3ModelContributionError> {
        if self.finished {
            return Ok(());
        }
        let identity = self
            .retained
            .as_ref()
            .ok_or_else(|| cleanup_error(&self.path, "output identity is unavailable"))?;
        remove_file_if_identity(&self.path, identity)?;
        self.retained.take();
        self.finished = true;
        Ok(())
    }

    fn confirm(&mut self) {
        self.retained.take();
        self.finished = true;
    }
}

impl Drop for PublishedContributionOutput {
    fn drop(&mut self) {
        if !self.finished
            && let Some(identity) = self.retained.as_ref()
        {
            let _ = remove_file_if_identity(&self.path, identity);
        }
        self.retained.take();
    }
}

